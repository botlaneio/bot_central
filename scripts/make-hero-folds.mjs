const f = n => +n.toFixed(1);
const SPACING = 2.6; // px between strands

function strands(fold, i) {
  // Lines run along `angle`, stepped across the fold's bounding box, each gently bowed and slightly wavy.
  const xs = fold.pts.map(p => p[0]), ys = fold.pts.map(p => p[1]);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2, cy = (Math.min(...ys) + Math.max(...ys)) / 2;
  const half = Math.hypot(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) / 2 + 20;
  const a = (fold.angle * Math.PI) / 180, dx = Math.cos(a), dy = Math.sin(a), nx = -dy, ny = dx;
  let d = "";
  let k = 0;
  for (let o = -half; o <= half; o += SPACING, k++) {
    const wob = Math.sin(k * 0.37 + i) * 3 + Math.sin(k * 0.11) * 5; // slow wave across the strands
    const bx = cx + nx * o, by = cy + ny * o;
    const x0 = bx - dx * half, y0 = by - dy * half, x1 = bx + dx * half, y1 = by + dy * half;
    const bow = fold.curve * Math.cos((o / half) * Math.PI) + wob;
    const qx = bx + nx * bow, qy = by + ny * bow;
    d += `M${f(x0)} ${f(y0)}Q${f(qx)} ${f(qy)} ${f(x1)} ${f(y1)}`;
  }
  return d;
}

function svg(name, palettes) {
  let defs = "", body = "";
  folds.forEach((fold, i) => {
    const pts = fold.pts.map(p => p.join(",")).join(" ");
    const a = (fold.angle * Math.PI) / 180;
    // Gradient across the strands (perpendicular to their run), so colour bands sweep over the fibres.
    const gx = 0.5 - Math.sin(a) * 0.5, gy = 0.5 + Math.cos(a) * 0.5;
    const stops = palettes[i].map((c, j) => `<stop offset="${j / (palettes[i].length - 1)}" stop-color="${c}"/>`).join("");
    defs += `<linearGradient id="g${i}" x1="${f(gx)}" y1="${f(1 - gy)}" x2="${f(1 - gx)}" y2="${f(gy)}">${stops}</linearGradient>`;
    defs += `<linearGradient id="h${i}" gradientUnits="objectBoundingBox" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#ffffff" stop-opacity=".32"/><stop offset=".5" stop-color="#ffffff" stop-opacity="0"/><stop offset="1" stop-color="#061b31" stop-opacity=".25"/></linearGradient>`;
    defs += `<clipPath id="c${i}"><polygon points="${pts}"/></clipPath>`;
    body += `<g clip-path="url(#c${i})">`;
    body += `<polygon points="${pts}" fill="url(#g${i})" opacity=".85"/>`; // base glow between strands
    body += `<path d="${strands(fold, i)}" fill="none" stroke="url(#g${i})" stroke-width="1.4"/>`; // the fibres
    body += `<path d="${strands({ ...fold, curve: fold.curve * -0.6 }, i + 2)}" fill="none" stroke="#ffffff" stroke-opacity=".22" stroke-width=".5"/>`; // highlights
    body += `<polygon points="${pts}" fill="url(#h${i})"/>`; // sheen: light to shadow
    body += `</g>`;
  });
  body += `<g fill="none" stroke="#ffffff" stroke-opacity=".7" stroke-width="1"><polyline points="640,420 880,330 1010,0"/><polyline points="880,330 1060,420 1280,140"/><polyline points="1060,420 960,720"/></g>`;
  return `<svg preserveAspectRatio="none" xmlns="http://www.w3.org/2000/svg" viewBox="600 0 680 720" width="680" height="720">
<!-- botLane hero: folded planes as fine iridescent strands (${name}). Original artwork; generated by scripts/make-hero-folds.mjs. -->
<defs>${defs}</defs>${body}
</svg>
`;
}

for (const [file, palettes] of Object.entries(states)) fs.writeFileSync(`public/media/${file}`, svg(file, palettes));
