// Generates the homepage hero artwork (public/media/hero-folds*.svg): the "folded planes" composition (option C)
// rendered as dense, hair-thin flowing strands, like a nano-fibre surface, so the colour shimmers up close and reads
// as a smooth gradient from a distance. Three colour states; the page crossfades them. Original artwork.
// Run: node scripts/make-hero-folds.mjs
import fs from "node:fs";

const folds = [
  { pts: [[760, 0], [1010, 0], [880, 330], [640, 420]], angle: 64, curve: 18 },
  { pts: [[880, 330], [1010, 0], [1280, 0], [1280, 140], [1060, 420]], angle: -36, curve: -22 },
  { pts: [[640, 420], [880, 330], [1060, 420], [960, 720], [700, 720]], angle: 78, curve: 14 },
  { pts: [[1060, 420], [1280, 140], [1280, 720], [960, 720]], angle: -56, curve: -16 },
];

